#!/usr/bin/env python3
"""Temporary A/B research: indicators as overlays on existing strategy signals.

Research branch only; do not merge.

The base signals are generated by the repository's *existing* production
analysis path, not reimplemented here:

    core.paper_trading.strategy_registry.analyze_for_strategy

Each historical decision uses exactly the latest 120 completed bars, matching
the default live public-kline runner limit. Only HIGH/MEDIUM candidates are
eligible because `run_enabled_strategies.py` only forwards those candidates to
the TradeIntent pipeline.

Stage-1 scope is deliberately bounded to current 15m + 1h strategies:

MACD rebound (BTC/ETH/BNB/SUI/1000PEPE):
- BASELINE
- ACCEL_POSITIVE_NON_EXTREME: signed_speed > 0 and regime != EXTREME
- IRON_TOP_VETO: reject when Iron Top strength >= 1

Weak short (XRP/ARB/DOGE):
- BASELINE
- ACCEL_NEGATIVE_NON_EXTREME: signed_speed < 0 and regime != EXTREME
- BOTTOM_REVERSAL_VETO: reject exact known price event
  (prior-30 new low + close above previous bar low)
- IRON_TOP_CONFIRM: require Iron Top strength >= 1

No overlay combinations, no threshold tuning, no symbol selection, no 5m in
this stage. Entry is next-bar open after a completed signal bar. Existing
candidate stop/target prices are preserved; executable geometry is revalidated
at the actual next-bar fill. One exposure at a time per
strategy/symbol/timeframe/variant. Fee grid is 0 and 0.5 bp per side with zero
slippage; the 0.5 bp value is a transparent research stress input, NOT P1-03.
"""
